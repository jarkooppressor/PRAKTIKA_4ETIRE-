#include <stdio.h>

int main(void) {
    int n;
    int sum = 0;
    int i = 1;

    if (scanf("%d", &n) != 1 || n <= 0) {
        return 1;
}
/* Суммируем все делители числа, кроме самого числа */
    while (i < n) {
        if (n % i == 0) {
            sum += i;   
/* оператор += накапливает сумму */
}
    i++;
}
    if (sum == n) {
        printf("%d - совершенное число\n", n);
}   else {
        printf("%d - не совершенное число\n", n);
}

    return 0;
}    
    /* Оператор += удобно юзать, потому что он позволяет писать
     * sum += i вместо sum = sum + i.
     * Аналогично *= используется для накопления произведения.*/